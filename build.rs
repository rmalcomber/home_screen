// Embeds the web app. `npm run build` in web/ leaves a gzip copy of every file in web/dist (web/scripts/pack.mjs);
// this turns each one into an `include_bytes!` entry. The server sends the bytes unchanged with
// `Content-Encoding: gzip`, so the exe carries no decompression code and no embedding crate.
use std::{env, fs, path::{Path, PathBuf}};

fn collect(dir: &Path, base: &Path, out: &mut Vec<(String, PathBuf)>) {
    let mut entries: Vec<_> = fs::read_dir(dir).expect("read web/dist").filter_map(|e| e.ok()).collect();
    entries.sort_by_key(|e| e.file_name());
    for e in entries {
        let p = e.path();
        if p.is_dir() {
            collect(&p, base, out);
        } else if p.extension().is_some_and(|x| x == "gz") {
            let rel = p.strip_prefix(base).unwrap().with_extension("");
            out.push((rel.to_string_lossy().replace('\\', "/"), p));
        }
    }
}

fn main() {
    let root = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let dist = root.join("web").join("dist");
    println!("cargo:rerun-if-changed={}", dist.display());
    println!("cargo:rerun-if-changed=build.rs");
    let mut files = Vec::new();
    if dist.is_dir() {
        collect(&dist, &dist, &mut files);
    }
    if !files.iter().any(|(n, _)| n == "index.html") {
        panic!("web/dist/index.html.gz not found: run `npm ci && npm run build` in web/ first (build.ps1 does it all)");
    }
    let mut src = String::from("// generated by build.rs\npub static ASSETS: &[(&str, &[u8])] = &[\n");
    for (name, path) in &files {
        println!("cargo:rerun-if-changed={}", path.display());
        src.push_str(&format!("    ({:?}, include_bytes!({:?})),\n", name, path.to_string_lossy()));
    }
    src.push_str("];\n");
    fs::write(PathBuf::from(env::var("OUT_DIR").unwrap()).join("assets.rs"), src).unwrap();
}
